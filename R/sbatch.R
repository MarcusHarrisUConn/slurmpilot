# SLURM sbatch array submission script & standalone worker runner generator

#' Generate the Standalone Base-R Cluster Worker Script
#'
#' Emits a self-contained R script (`worker.R`) that executes one SLURM array
#' chunk on a compute node with zero dependency on `slurmpilot` itself. The
#' worker loads `payload.rds` and `chunks.rds`, skips chunks that already have
#' valid completed checkpoints, runs assigned tasks deterministically, writes
#' atomic `.rds` result checkpoints and `.json` status telemetry, and propagates
#' non-zero exit codes on task failure.
#'
#' @param output_path Optional file path to write `worker.R`.
#'
#' @return Character vector of script lines (invisibly if `output_path` is
#'   provided, otherwise visibly).
#' @seealso [render_sbatch_script()]
#' @export
#' @examples
#' script_lines <- render_worker_script()
#' head(script_lines, 10)
render_worker_script <- function(output_path = NULL) {
  if (!is.null(output_path)) {
    checkmate::assert_string(output_path, min.chars = 1L)
  }

  lines <- c(
    "#!/usr/bin/env Rscript",
    "# Auto-generated by slurmpilot: standalone zero-dependency array chunk worker",
    "",
    "parse_cli_args <- function(args) {",
    "  out <- list(",
    "    work_dir = Sys.getenv('SLURMPILOT_WORK_DIR', unset = getwd()),",
    "    chunk_id = Sys.getenv('SLURMPILOT_CHUNK_ID', unset = Sys.getenv('SLURM_ARRAY_TASK_ID', unset = '')),",
    "    attempt = Sys.getenv('SLURMPILOT_ATTEMPT', unset = '1'),",
    "    force = FALSE",
    "  )",
    "  i <- 1L",
    "  while (i <= length(args)) {",
    "    a <- args[[i]]",
    "    if (a == '--work-dir' && i < length(args)) {",
    "      out$work_dir <- args[[i + 1L]]; i <- i + 2L",
    "    } else if (a == '--chunk-id' && i < length(args)) {",
    "      out$chunk_id <- args[[i + 1L]]; i <- i + 2L",
    "    } else if (a == '--attempt' && i < length(args)) {",
    "      out$attempt <- args[[i + 1L]]; i <- i + 2L",
    "    } else if (a == '--force') {",
    "      out$force <- TRUE; i <- i + 1L",
    "    } else {",
    "      i <- i + 1L",
    "    }",
    "  }",
    "  out",
    "}",
    "",
    "json_escape <- function(x) {",
    "  x <- gsub('\\\\', '\\\\\\\\', x, fixed = TRUE)",
    "  x <- gsub('\"', '\\\\\"', x, fixed = TRUE)",
    "  x <- gsub('\\n', '\\\\n', x, fixed = TRUE)",
    "  x <- gsub('\\r', '\\\\r', x, fixed = TRUE)",
    "  x <- gsub('\\t', '\\\\t', x, fixed = TRUE)",
    "  x",
    "}",
    "",
    "to_simple_json <- function(lst) {",
    "  entries <- vapply(names(lst), function(nm) {",
    "    val <- lst[[nm]]",
    "    encoded <- if (is.null(val) || (length(val) == 1L && is.na(val))) {",
    "      'null'",
    "    } else if (is.logical(val)) {",
    "      if (isTRUE(val[[1L]])) 'true' else 'false'",
    "    } else if (is.numeric(val)) {",
    "      if (is.finite(val[[1L]])) format(val[[1L]], scientific = FALSE, trim = TRUE) else 'null'",
    "    } else {",
    "      paste0('\"', json_escape(as.character(val[[1L]])), '\"')",
    "    }",
    "    paste0('  \"', json_escape(nm), '\": ', encoded)",
    "  }, character(1L))",
    "  paste0('{\\n', paste(entries, collapse = ',\\n'), '\\n}')",
    "}",
    "",
    "write_atomic_lines <- function(txt, path) {",
    "  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)",
    "  tmp <- file.path(dirname(path), paste0('.', basename(path), '.tmp.', Sys.getpid()))",
    "  writeLines(txt, con = tmp, useBytes = TRUE)",
    "  if (!file.rename(tmp, path)) {",
    "    file.copy(tmp, path, overwrite = TRUE)",
    "    unlink(tmp)",
    "  }",
    "}",
    "",
    "write_atomic_rds <- function(obj, path) {",
    "  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)",
    "  tmp <- file.path(dirname(path), paste0('.', basename(path), '.tmp.', Sys.getpid()))",
    "  saveRDS(obj, file = tmp)",
    "  if (!file.rename(tmp, path)) {",
    "    file.copy(tmp, path, overwrite = TRUE)",
    "    unlink(tmp)",
    "  }",
    "}",
    "",
    "read_linux_vmhwm_mb <- function() {",
    "  if (!file.exists('/proc/self/status')) return(NA_real_)",
    "  st <- tryCatch(readLines('/proc/self/status', warn = FALSE), error = function(e) character())",
    "  hit <- grep('^VmHWM:', st, value = TRUE)",
    "  if (length(hit) == 0L) return(NA_real_)",
    "  kb <- suppressWarnings(as.numeric(gsub('[^0-9.]', '', hit[[1L]])))",
    "  if (is.na(kb)) NA_real_ else kb / 1024",
    "}",
    "",
    "utc_now <- function() format(Sys.time(), '%Y-%m-%dT%H:%M:%OS3Z', tz = 'UTC')",
    "",
    "opts <- parse_cli_args(commandArgs(trailingOnly = TRUE))",
    "work_dir <- opts$work_dir",
    "chunk_id <- suppressWarnings(as.integer(opts$chunk_id))",
    "attempt <- suppressWarnings(as.integer(opts$attempt))",
    "if (is.na(attempt) || attempt < 1L) attempt <- 1L",
    "if (is.na(chunk_id) || chunk_id < 1L) {",
    "  stop('Missing or invalid chunk_id (--chunk-id or SLURM_ARRAY_TASK_ID).')",
    "}",
    "",
    "result_path <- file.path(work_dir, 'results', sprintf('chunk_%04d.rds', chunk_id))",
    "status_path <- file.path(work_dir, 'status', sprintf('chunk_%04d.json', chunk_id))",
    "",
    "# Idempotent checkpoint skip when already completed",
    "if (!isTRUE(opts$force) && file.exists(result_path) && file.exists(status_path)) {",
    "  prev_txt <- paste(readLines(status_path, warn = FALSE), collapse = ' ')",
    "  if (grepl('\"COMPLETED\"', prev_txt, fixed = TRUE)) {",
    "    cat(sprintf('[slurmpilot] Chunk %d already completed; reusing checkpoint.\\n', chunk_id))",
    "    quit(save = 'no', status = 0L)",
    "  }",
    "}",
    "",
    "started_at <- utc_now()",
    "t0 <- proc.time()[['elapsed']]",
    "",
    "cpus <- Sys.getenv('SLURM_CPUS_PER_TASK', unset = '')",
    "if (nzchar(cpus)) {",
    "  Sys.setenv(OMP_NUM_THREADS = cpus, OPENBLAS_NUM_THREADS = cpus, MKL_NUM_THREADS = cpus)",
    "}",
    "",
    "payload <- readRDS(file.path(work_dir, 'payload.rds'))",
    "chunks <- readRDS(file.path(work_dir, 'chunks.rds'))",
    "row_idx <- which(chunks$chunk_id == chunk_id)",
    "if (length(row_idx) != 1L) {",
    "  stop(sprintf('Chunk %d not found in chunks.rds', chunk_id))",
    "}",
    "task_indices <- chunks$task_indices[[row_idx]]",
    "",
    "# Optional mock fault injection (used strictly by MockSlurmBackend tests/demos)",
    "mock_fault <- Sys.getenv('SLURMPILOT_MOCK_FAULT', unset = '')",
    "if (nzchar(mock_fault)) {",
    "  wall_sec <- max(0, proc.time()[['elapsed']] - t0)",
    "  if (mock_fault == 'OOM') {",
    "    msg <- sprintf('Simulated OUT_OF_MEMORY kill on chunk %d (attempt %d)', chunk_id, attempt)",
    "    cat(msg, '\\n', file = stderr())",
    "    write_atomic_lines(to_simple_json(list(",
    "      chunk_id = chunk_id, state = 'OUT_OF_MEMORY', attempt = attempt,",
    "      started_at = started_at, finished_at = utc_now(), wall_sec = wall_sec,",
    "      n_tasks = length(task_indices), n_ok = 0L, n_failed = length(task_indices),",
    "      peak_rss_mb = read_linux_vmhwm_mb(), exit_code = 137L,",
    "      error_message = msg, checkpoint_exists = FALSE",
    "    )), status_path)",
    "    quit(save = 'no', status = 137L)",
    "  } else if (mock_fault == 'TIMEOUT') {",
    "    msg <- sprintf('Simulated TIMEOUT kill on chunk %d (attempt %d)', chunk_id, attempt)",
    "    cat(msg, '\\n', file = stderr())",
    "    write_atomic_lines(to_simple_json(list(",
    "      chunk_id = chunk_id, state = 'TIMEOUT', attempt = attempt,",
    "      started_at = started_at, finished_at = utc_now(), wall_sec = wall_sec,",
    "      n_tasks = length(task_indices), n_ok = 0L, n_failed = length(task_indices),",
    "      peak_rss_mb = read_linux_vmhwm_mb(), exit_code = 124L,",
    "      error_message = msg, checkpoint_exists = FALSE",
    "    )), status_path)",
    "    quit(save = 'no', status = 124L)",
    "  } else if (mock_fault == 'FAIL') {",
    "    msg <- sprintf('Simulated worker failure on chunk %d (attempt %d)', chunk_id, attempt)",
    "    cat(msg, '\\n', file = stderr())",
    "    write_atomic_lines(to_simple_json(list(",
    "      chunk_id = chunk_id, state = 'FAILED', attempt = attempt,",
    "      started_at = started_at, finished_at = utc_now(), wall_sec = wall_sec,",
    "      n_tasks = length(task_indices), n_ok = 0L, n_failed = length(task_indices),",
    "      peak_rss_mb = read_linux_vmhwm_mb(), exit_code = 1L,",
    "      error_message = msg, checkpoint_exists = FALSE",
    "    )), status_path)",
    "    quit(save = 'no', status = 1L)",
    "  }",
    "}",
    "",
    "for (pkg in payload$packages) {",
    "  suppressPackageStartupMessages(library(pkg, character.only = TRUE))",
    "}",
    "",
    "fn <- payload$fun",
    "if (length(payload$globals) > 0L) {",
    "  parent_env <- environment(fn)",
    "  if (is.null(parent_env)) parent_env <- globalenv()",
    "  environment(fn) <- list2env(payload$globals, parent = parent_env)",
    "}",
    "",
    "cat(sprintf('[slurmpilot] Chunk %d (attempt %d): running %d task(s) [%s]\\n',",
    "            chunk_id, attempt, length(task_indices), paste(task_indices, collapse = ',')))",
    "",
    "results <- vector('list', length(task_indices))",
    "names(results) <- as.character(task_indices)",
    "task_errors <- character(0L)",
    "n_ok <- 0L",
    "",
    "for (i in seq_along(task_indices)) {",
    "  tid <- task_indices[[i]]",
    "  if (!is.null(payload$seed)) {",
    "    set.seed(as.integer(payload$seed + tid))",
    "  }",
    "  res <- tryCatch(",
    "    {",
    "      val <- fn(payload$args_list[[tid]])",
    "      n_ok <- n_ok + 1L",
    "      list(ok = TRUE, task_index = tid, value = val, error = NA_character_)",
    "    },",
    "    error = function(e) {",
    "      msg <- conditionMessage(e)",
    "      task_errors <<- c(task_errors, sprintf('task %d: %s', tid, msg))",
    "      cat(sprintf('[slurmpilot] ERROR in task %d: %s\\n', tid, msg), file = stderr())",
    "      list(ok = FALSE, task_index = tid, value = NULL, error = msg)",
    "    }",
    "  )",
    "  results[[i]] <- res",
    "}",
    "",
    "n_failed <- length(task_indices) - n_ok",
    "wall_sec <- max(0, proc.time()[['elapsed']] - t0)",
    "peak_rss <- read_linux_vmhwm_mb()",
    "succeeded <- (n_failed == 0L)",
    "",
    "checkpoint_written <- FALSE",
    "if (succeeded || isTRUE(payload$continue_on_error)) {",
    "  write_atomic_rds(list(",
    "    chunk_id = chunk_id,",
    "    attempt = attempt,",
    "    task_indices = task_indices,",
    "    results = results,",
    "    wall_sec = wall_sec,",
    "    finished_at = utc_now()",
    "  ), result_path)",
    "  checkpoint_written <- TRUE",
    "}",
    "",
    "state <- if (succeeded) 'COMPLETED' else 'FAILED'",
    "exit_code <- if (succeeded) 0L else 1L",
    "err_summary <- if (length(task_errors) > 0L) paste(task_errors, collapse = '; ') else NA_character_",
    "",
    "write_atomic_lines(to_simple_json(list(",
    "  chunk_id = chunk_id,",
    "  state = state,",
    "  attempt = attempt,",
    "  started_at = started_at,",
    "  finished_at = utc_now(),",
    "  wall_sec = wall_sec,",
    "  n_tasks = length(task_indices),",
    "  n_ok = n_ok,",
    "  n_failed = n_failed,",
    "  peak_rss_mb = peak_rss,",
    "  exit_code = exit_code,",
    "  error_message = err_summary,",
    "  checkpoint_exists = checkpoint_written",
    ")), status_path)",
    "",
    "cat(sprintf('[slurmpilot] Chunk %d finished with state=%s in %.2fs\\n', chunk_id, state, wall_sec))",
    "quit(save = 'no', status = exit_code)"
  )

  if (!is.null(output_path)) {
    sp_write_lines_atomic(lines, output_path)
    return(invisible(lines))
  }
  lines
}

#' Render a Self-Contained SLURM `sbatch` Array Submission Script
#'
#' Generates a POSIX/bash-safe SLURM batch script configured from a
#' `slurmpilot_resources` plan (with optional surgical array index overrides,
#' Apptainer container execution, environment modules, and structured logging).
#'
#' @param job_name Character SLURM `--job-name` (sanitized automatically).
#' @param resources A `slurmpilot_resources` object from [estimate_resources()]
#'   or [resource_spec()].
#' @param work_dir Remote or local working directory containing `payload.rds`,
#'   `chunks.rds`, and `worker_script`.
#' @param worker_script Filename or path of the worker script (default
#'   `"worker.R"`).
#' @param array_indices Optional integer vector overriding `--array` for
#'   surgical retries of specific failed chunks.
#' @param attempt Positive integer submission attempt number passed to
#'   `worker.R` via `SLURMPILOT_ATTEMPT`. Default `1L`.
#' @param container_sif Optional path to an Apptainer/Singularity `.sif` image.
#'   When supplied, wraps `Rscript` inside `apptainer exec --cleanenv`.
#' @param container_binds Optional character vector of Apptainer `--bind` mount
#'   specifications (e.g. `"/scratch:/scratch"`). `work_dir` is always bound
#'   automatically when `container_sif` is set.
#' @param modules Optional character vector of HPC environment modules to load
#'   via `module load`.
#' @param env_vars Optional named list or character vector of extra environment
#'   variables exported in the job script.
#' @param log_dir Subdirectory inside `work_dir` for SLURM stdout/stderr logs.
#'   Default `"logs"`.
#' @param mail_user Optional email address for `--mail-user`.
#' @param mail_type Optional SLURM `--mail-type` (e.g., `"END,FAIL"`).
#' @param extra_sbatch Optional character vector of extra raw `#SBATCH` flags
#'   (without leading `#SBATCH`).
#' @param output_path Optional file path to write the rendered `.sbatch` script.
#'
#' @return An S3 object of class `"slurmpilot_sbatch"` with `script` (character
#'   vector of lines), `text` (single string), `path`, `job_name`, `array_spec`,
#'   and `resources`.
#'
#' @seealso [estimate_resources()], [build_apptainer_def()],
#'   [render_worker_script()]
#' @export
#' @examples
#' res <- resource_spec(n_tasks = 40, chunk_size = 4, mem_mb = 2048, time_minutes = 20)
#' sb <- render_sbatch_script("mc_power", res, work_dir = "/scratch/user/mc_power")
#' cat(sb$text)
render_sbatch_script <- function(
  job_name,
  resources,
  work_dir,
  worker_script = "worker.R",
  array_indices = NULL,
  attempt = 1L,
  container_sif = NULL,
  container_binds = character(),
  modules = character(),
  env_vars = list(),
  log_dir = "logs",
  mail_user = NULL,
  mail_type = NULL,
  extra_sbatch = character(),
  output_path = NULL
) {
  checkmate::assert_string(job_name, min.chars = 1L)
  checkmate::assert_class(resources, "slurmpilot_resources")
  checkmate::assert_string(work_dir, min.chars = 1L)
  checkmate::assert_string(worker_script, min.chars = 1L)
  if (!is.null(array_indices)) {
    checkmate::assert_integerish(array_indices, lower = 1L, upper = resources$n_chunks, min.len = 1L)
  }
  checkmate::assert_int(attempt, lower = 1L)
  if (!is.null(container_sif)) checkmate::assert_string(container_sif, min.chars = 1L)
  checkmate::assert_character(container_binds, any.missing = FALSE)
  checkmate::assert_character(modules, any.missing = FALSE)
  checkmate::assert_string(log_dir, min.chars = 1L)
  if (!is.null(mail_user)) checkmate::assert_string(mail_user, min.chars = 1L)
  if (!is.null(mail_type)) checkmate::assert_string(mail_type, min.chars = 1L)
  checkmate::assert_character(extra_sbatch, any.missing = FALSE)
  if (!is.null(output_path)) checkmate::assert_string(output_path, min.chars = 1L)

  safe_name <- sp_sanitize_name(job_name)
  flags <- as_slurm_flags(resources, array_indices = array_indices)
  array_spec <- sub("^--array=", "", flags[grepl("^--array=", flags)][[1L]])

  log_path_prefix <- file.path(work_dir, log_dir)
  header <- c(
    "#!/usr/bin/env bash",
    paste0("#SBATCH --job-name=", safe_name),
    paste0("#SBATCH ", flags),
    paste0("#SBATCH --output=", log_path_prefix, "/chunk_%a.out"),
    paste0("#SBATCH --error=", log_path_prefix, "/chunk_%a.err")
  )
  if (!is.null(mail_user)) {
    header <- c(header, paste0("#SBATCH --mail-user=", mail_user))
  }
  if (!is.null(mail_type)) {
    header <- c(header, paste0("#SBATCH --mail-type=", mail_type))
  }
  if (length(extra_sbatch) > 0L) {
    header <- c(header, paste0("#SBATCH ", trimws(extra_sbatch)))
  }

  body <- c(
    "",
    "set -euo pipefail",
    "",
    paste0("WORK_DIR=", sp_sh_quote(work_dir)),
    "mkdir -p \"${WORK_DIR}/logs\" \"${WORK_DIR}/results\" \"${WORK_DIR}/status\"",
    "cd \"${WORK_DIR}\""
  )

  if (length(modules) > 0L) {
    body <- c(
      body,
      "",
      "# Load HPC environment modules",
      vapply(modules, function(m) paste0("module load ", m), character(1L), USE.NAMES = FALSE)
    )
  }

  # Threading & slurmpilot runtime exports
  body <- c(
    body,
    "",
    paste0("export OMP_NUM_THREADS=", resources$cpus_per_task),
    paste0("export OPENBLAS_NUM_THREADS=", resources$cpus_per_task),
    paste0("export MKL_NUM_THREADS=", resources$cpus_per_task),
    "export SLURMPILOT_WORK_DIR=\"${WORK_DIR}\"",
    "export SLURMPILOT_CHUNK_ID=\"${SLURM_ARRAY_TASK_ID}\"",
    paste0("export SLURMPILOT_ATTEMPT=", attempt)
  )

  if (length(env_vars) > 0L) {
    ev_names <- names(env_vars)
    for (i in seq_along(env_vars)) {
      body <- c(body, sprintf("export %s=%s", ev_names[[i]], sp_sh_quote(as.character(env_vars[[i]]))))
    }
  }

  worker_arg <- if (grepl("^/", worker_script)) worker_script else file.path("${WORK_DIR}", worker_script)
  exec_line <- if (!is.null(container_sif)) {
    all_binds <- unique(c(paste0(work_dir, ":", work_dir), container_binds))
    bind_flags <- paste(vapply(all_binds, function(b) paste0("--bind ", sp_sh_quote(b)), character(1L)), collapse = " ")
    sprintf(
      "apptainer exec --cleanenv %s %s Rscript \"%s\" --work-dir \"${WORK_DIR}\" --chunk-id \"${SLURM_ARRAY_TASK_ID}\" --attempt \"%d\"",
      bind_flags,
      sp_sh_quote(container_sif),
      worker_arg,
      attempt
    )
  } else {
    sprintf(
      "Rscript \"%s\" --work-dir \"${WORK_DIR}\" --chunk-id \"${SLURM_ARRAY_TASK_ID}\" --attempt \"%d\"",
      worker_arg,
      attempt
    )
  }

  body <- c(
    body,
    "",
    "echo \"[slurmpilot] Starting job ${SLURM_JOB_ID:-local} array task ${SLURM_ARRAY_TASK_ID} on $(hostname)\"",
    exec_line
  )

  lines <- c(header, body)

  if (!is.null(output_path)) {
    sp_write_lines_atomic(lines, output_path)
  }

  structure(
    list(
      script = lines,
      text = paste(lines, collapse = "\n"),
      path = output_path,
      job_name = safe_name,
      array_spec = array_spec,
      attempt = attempt,
      container_sif = container_sif,
      resources = resources
    ),
    class = "slurmpilot_sbatch"
  )
}

#' @export
as.character.slurmpilot_sbatch <- function(x, ...) {
  x$text
}

#' @export
print.slurmpilot_sbatch <- function(x, ...) {
  cli::cli_h3("slurmpilot SLURM Batch Script ({x$job_name})")
  cli::cli_bullets(c(
    "*" = "Array: {x$array_spec} | Attempt: {x$attempt} | Lines: {length(x$script)}",
    "*" = "Container: {if (is.null(x$container_sif)) 'native Rscript' else x$container_sif}"
  ))
  if (!is.null(x$path)) {
    cli::cli_bullets(c("v" = "Written to: {.path {x$path}}"))
  }
  invisible(x)
}
